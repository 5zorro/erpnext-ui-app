#!/usr/bin/env node
/**
 * Simplified's Doc-skin defaults, generated (5zorro 2026-10-10). See src/simplified-seed-rule.js.
 *
 *   npm run seeds:simplified                 regenerate src/simplified-seed-profiles.generated.js
 *   npm run seeds:simplified -- --check      exit 1 if the committed file is out of date (writes nothing)
 *   npm run seeds:simplified -- --refresh-meta
 *       re-read each DocType's fields from the local ERPNext clone first (after an ERPNext
 *       upgrade). Reads with `git show <ref>:<path>`, so the clone's checked-out branch does not
 *       matter. ERPNEXT_REPO (default ~/erpnext/erpnext) and ERPNEXT_REF (default the snapshot's
 *       own ref, else sandbox-v16.32.1 — the tag matching the running instance).
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { SEED_RULE_CONFIG, deriveAllSeeds } from "../src/simplified-seed-rule.js";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const META_DIR = path.join(ROOT, "tests", "fixtures", "simplified-seed-meta");
const OUT = path.join(ROOT, "src", "simplified-seed-profiles.generated.js");
const DEFAULT_REF = "sandbox-v16.32.1";

/** Keep only what the rule reads, so a snapshot diff after an upgrade is readable. */
function slimField(f) {
  const out = { fieldname: f.fieldname, fieldtype: f.fieldtype || "Data" };
  for (const k of ["reqd", "hidden", "read_only"]) if (f[k]) out[k] = 1;
  return out;
}

function refreshMeta() {
  const repo = process.env.ERPNEXT_REPO || path.join(os.homedir(), "erpnext", "erpnext");
  for (const [doctype, cfg] of Object.entries(SEED_RULE_CONFIG)) {
    const file = path.join(META_DIR, cfg.snapshot);
    const prior = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : null;
    const ref = process.env.ERPNEXT_REF || (prior && prior.erpnextRef) || DEFAULT_REF;
    const raw = execFileSync("git", ["-C", repo, "show", `${ref}:${cfg.source.path}`], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
    const json = JSON.parse(raw);
    const snap = { doctype, erpnextRef: ref, source: cfg.source.path, fields: (json.fields || []).map(slimField) };
    fs.mkdirSync(META_DIR, { recursive: true });
    fs.writeFileSync(file, `${JSON.stringify(snap, null, 1)}\n`);
    console.log(`snapshot ${doctype}: ${snap.fields.length} fields @ ${ref}`);
  }
}

/** @returns {{ fieldsByDoctype: Record<string, any[]>, refs: string[] }} */
export function readMeta() {
  const fieldsByDoctype = {};
  const refs = new Set();
  for (const [doctype, cfg] of Object.entries(SEED_RULE_CONFIG)) {
    const snap = JSON.parse(fs.readFileSync(path.join(META_DIR, cfg.snapshot), "utf8"));
    fieldsByDoctype[doctype] = snap.fields;
    refs.add(snap.erpnextRef);
  }
  return { fieldsByDoctype, refs: [...refs] };
}

/** The generated module's text — also what the drift test compares against. */
export function renderGenerated({ profiles, values }, refs) {
  const freeze = (obj, indent) =>
    `Object.freeze({\n${Object.entries(obj)
      .map(([k, v]) => `${indent}  ${JSON.stringify(k)}: ${typeof v === "object" ? freeze(v, `${indent}  `) : JSON.stringify(v)},`)
      .join("\n")}\n${indent}})`;
  return `/**
 * GENERATED by \`npm run seeds:simplified\` (scripts/generate-simplified-seeds.js) from
 * tests/fixtures/simplified-seed-meta/ (ERPNext ${refs.join(", ")}) and src/simplified-seed-rule.js.
 * Do not edit by hand: change the rule or the Doc skin, then regenerate. The drift test
 * (tests/simplified-seed-generator.test.js) fails while this file and the rule disagree.
 */

/** @type {Readonly<Record<string, Readonly<Record<string, "L1"|"L2">>>>} */
export const GENERATED_SEED_PROFILES = ${freeze(profiles, "")};

/** @type {Readonly<Record<string, Readonly<Record<string, { valueSource: "expr", expr: { base: "today"|"som"|"eom", offset: number } }>>>>} */
export const GENERATED_SEED_VALUES = ${freeze(values, "")};
`;
}

function main() {
  const args = new Set(process.argv.slice(2));
  if (args.has("--refresh-meta")) refreshMeta();
  const { fieldsByDoctype, refs } = readMeta();
  const text = renderGenerated(deriveAllSeeds(fieldsByDoctype), refs);
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (args.has("--check")) {
    if (current !== text) {
      console.error("simplified-seed-profiles.generated.js is out of date — run: npm run seeds:simplified");
      process.exit(1);
    }
    console.log("simplified seeds up to date");
    return;
  }
  if (current === text) {
    console.log("simplified seeds unchanged");
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
